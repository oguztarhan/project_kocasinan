def mk(arch, name, L, W, H, color, **over):
    b = A[arch]; s = {}
    for k in CURVE_H: s[k] = [(x, v*H) for (x, v) in b[k]]
    for k in CURVE_W: s[k] = [(x, v*W) for (x, v) in b[k]]
    for k in CURVE_F: s[k] = list(b[k])
    for k, v in b.items():
        if k not in CURVE_H + CURVE_W + CURVE_F and k != "bed": s[k] = v
    if "bed" in b:
        b0, b1, zf, hf = b["bed"]; s["bed"] = (b0, b1, zf*H, hf*H)
    s.update(name=name, length=L, color=color, arch_name=arch)
    s.update(over)
    return s

